export function translate(
  locale: Locale,
  key: TranslationKey,
  values: Record<string, string | number> = {},
): string {
  let message: string = locale === "tr" ? tr[key] : en[key];
  for (const [name, value] of Object.entries(values)) {
    message = message.split("{" + name + "}").join(String(value));
  }
  return message;
}
